"""Portable local CT/prediction pipeline, independent of existing local_* tools.

Clean -> watershed -> original merge -> optional CT stack splitting -> XYZ
stitching. All new dependencies are named portable_sheet_*. Original scripts
remain importable without local CLI extensions. Outputs use local_run.json and
global_table.json for downstream constraint tools; no winding constraints are
generated by this command.
"""

import argparse
import itertools
import json
from pathlib import Path
import time

import numpy as np

from vesuvius_sheet_tools.separate_sheets import CORE_DIST, MIN_CC, MIN_CORE
from vesuvius_sheet_tools.split_stacked import MEGA_FRAC, MIN_CENTER_CC
from sheet_compute import Compute
from sheet_io import Volume, write_json
from sheet_stitching import Stitcher
from sheet_progress import block_progress
from sheet_workers import block_results, result_labels


def block_starts(start, stop, size, overlap):
    """Cover an interval, clipping only the last block and avoiding redundant tails."""
    starts = [start]
    while starts[-1] + size < stop:
        starts.append(starts[-1] + size - overlap)
    return starts


def run(args):
    size, overlap = np.asarray(args.block_shape), np.asarray(args.overlap)
    if np.any(size < 1) or np.any(overlap < 1) or np.any(overlap >= size):
        raise ValueError("Require 1 <= overlap < block-shape in every dimension")
    if (args.min_cc < 1 or args.min_core < 1 or args.min_center < 1 or
            not np.isfinite(args.threshold) or not np.isfinite(args.core_dist) or
            args.core_dist <= 0 or not 0 < args.mega_frac <= 1):
        raise ValueError("Invalid threshold, component/seed size, core distance or mega fraction")
    if args.workers < 1:
        raise ValueError("--workers must be >= 1")
    if args.tensor_chunk_depth < 1 or args.eigh_chunk < 1:
        raise ValueError("Tensor chunk depth and eigh chunk must be positive")
    pred = Volume(args.pred, args.pred_dataset)
    ct = Volume(args.volume, args.ct_dataset)
    if pred.shape != ct.shape:
        raise ValueError(f"CT shape {ct.shape} differs from prediction {pred.shape}; align/resample first")
    if not all(pred.shape):
        raise ValueError("Input volumes must have nonempty ZYX dimensions")
    z1 = pred.shape[0] if args.z1 is None else args.z1
    if not 0 <= args.z0 < z1 <= pred.shape[0]:
        raise ValueError(f"Require 0 <= z0 < z1 <= {pred.shape[0]}")
    out = args.out
    if not args.resume and out.exists() and any(out.iterdir()):
        raise ValueError(f"Output directory must be empty: {out}")
    starts = [block_starts(lo, hi, int(n), int(o)) for lo, hi, n, o in
              zip((args.z0, 0, 0), (z1, *pred.shape[1:]), size, overlap)]
    total = int(np.prod([len(s) for s in starts]))
    config = {k: str(v.resolve()) if isinstance(v, Path) else v
              for k, v in vars(args).items() if k not in ("resume", "workers", "no_progress")}
    config.update(source_shape_zyx=list(pred.shape), z1=z1, axis_order="ZYX", pipeline="portable_sheet", pipeline_version=1)
    if args.resume:
        config_path = out / "pipeline_config.json"
        if not config_path.exists():
            raise ValueError("--resume requires an existing pipeline_config.json from this pipeline version")
        previous_config = json.loads(config_path.read_text(encoding="utf-8"))
        if not isinstance(previous_config, dict):
            raise ValueError("Invalid pipeline_config.json: expected an object")
        if previous_config != config:
            differing = sorted(k for k in previous_config.keys() | config.keys()
                               if previous_config.get(k) != config.get(k))
            raise ValueError(f"Resume configuration differs: {', '.join(differing)}; "
                             "reuse the original parameters and unchanged input volumes")
    compute = Compute(args.device, args.tensor_chunk_depth, args.eigh_chunk, args.oom_policy)
    out.mkdir(parents=True, exist_ok=True)
    write_json(out / "pipeline_config.json", config)
    status = dict(complete=False, expected_blocks=total, processed_blocks=0, reused_blocks=0,
                  workers=args.workers)
    write_json(out / "pipeline_status.json", status)
    stitcher, blocks, by_origin = Stitcher(out), [], {}
    started = time.monotonic()

    def jobs():
        for index, grid in enumerate(itertools.product(*(range(len(s)) for s in starts))):
            origin = tuple(starts[axis][g] for axis, g in enumerate(grid))
            shape = tuple(min(int(n), hi - o) for n, hi, o in
                          zip(size, (z1, *pred.shape[1:]), origin))
            yield index, grid, origin, shape, total

    with block_progress(total, args.device, args.workers, args.no_progress) as progress:
        with block_results(args, jobs(), pred, ct, compute) as results:
            for result in results:
                tick = time.monotonic()
                block, stats, grid = result["block"], result["stats"], result["grid"]
                origin = tuple(block["origin_zyx"])
                with result_labels(result) as labels:
                    stitcher.cache_faces(block, labels, grid, starts, overlap)
                    for axis in range(3):
                        if grid[axis] == 0:
                            continue
                        neighbor = list(origin)
                        neighbor[axis] = starts[axis][grid[axis] - 1]
                        stitcher.link(by_origin[tuple(neighbor)], block, labels, axis)
                if result["reused"]:
                    status["reused_blocks"] += 1
                else:
                    stats["stage_seconds"]["stitch"] = round(time.monotonic() - tick, 3)
                    stats["seconds"] = round(result["elapsed"] + time.monotonic() - tick, 3)
                    stats["checkpoint"] = block
                    # Only the coordinator commits, after archive, preview and stitching.
                    write_json((out / block["block"]).with_suffix(".json"), stats)
                blocks.append(block)
                by_origin[origin] = block
                status.update(processed_blocks=len(blocks), seconds=round(time.monotonic() - started, 3))
                write_json(out / "pipeline_status.json", status)
                progress.set_postfix(reused=status["reused_blocks"], refresh=False)
                progress.update(1)
                # Drop the serial result before requesting the next block.
                del labels, result
        progress.set_description("Finalizing IDs", refresh=True)
        metrics = stitcher.finish(blocks)
        write_json(out / "local_run.json", dict(axis_order="ZYX", crops=blocks,
                                               pipeline_config="pipeline_config.json"))
        status.update(complete=True, seconds=round(time.monotonic() - started, 3))
        write_json(out / "pipeline_status.json", status)
        progress.set_description("Done", refresh=True)
    progress.write(f"Done: {len(blocks)} blocks, {metrics['global_instances']} global instances "
                   f"in {status['seconds']:.1f}s. Output: {out.resolve()}")
    return metrics


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--volume", "--ct", required=True, type=Path, help="Aligned original CT")
    parser.add_argument("--pred", required=True, type=Path, help="Aligned surface prediction")
    parser.add_argument("--ct-dataset", help="Array path inside a CT Zarr group")
    parser.add_argument("--pred-dataset", help="Array path inside a prediction Zarr group")
    parser.add_argument("--out", type=Path, default=Path("output/portable_sheet_pipeline"))
    parser.add_argument("--block-shape", type=int, nargs=3, default=[64, 256, 256], metavar=("Z", "Y", "X"))
    parser.add_argument("--overlap", type=int, nargs=3, default=[16, 32, 32], metavar=("Z", "Y", "X"))
    parser.add_argument("--z0", type=int, default=0)
    parser.add_argument("--z1", type=int, help="Exclusive; default: full depth")
    parser.add_argument("--threshold", type=float, default=0, help="Prediction > threshold; default for binary masks")
    parser.add_argument("--min-cc", type=int, default=MIN_CC)
    parser.add_argument("--core-dist", type=float, default=CORE_DIST)
    parser.add_argument("--min-core", type=int, default=MIN_CORE)
    parser.add_argument("--no-merge", action="store_true")
    parser.add_argument("--no-ct-gating", action="store_true", help="Skip CT > 0 gating for unmasked CT")
    parser.add_argument("--no-split", action="store_true", help="Skip CT-based splitting of fused stacks")
    parser.add_argument("--mega-frac", type=float, default=MEGA_FRAC)
    parser.add_argument("--min-center", type=int, default=MIN_CENTER_CC)
    parser.add_argument("--no-previews", action="store_true")
    parser.add_argument("--device", choices=("cpu", "cuda"), default="cpu",
                        help="Backend for components, EDT, seeds and CT structure tensor/eigh")
    parser.add_argument("--tensor-chunk-depth", type=int, default=16,
                        help="Z slices per structure tensor workspace (plus Gaussian halo)")
    parser.add_argument("--eigh-chunk", type=int, default=500_000,
                        help="Maximum 3x3 matrices per eigenvalue batch")
    parser.add_argument("--oom-policy", choices=("cpu", "error"), default="cpu",
                        help="On CUDA out-of-memory, report and retry the stage on CPU, or stop")
    parser.add_argument("--workers", type=int, default=1,
                        help="Independent block processes; default 1 (serial). GPU stages share a lock.")
    parser.add_argument("--no-progress", action="store_true",
                        help="Disable the progress bar; warnings and final summary remain visible")
    parser.add_argument("--resume", action="store_true",
                        help="Reuse committed blocks with identical configuration; rebuild stitching")
    args = parser.parse_args(argv)
    try:
        run(args)
    except (ValueError, OSError, KeyError, TypeError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
